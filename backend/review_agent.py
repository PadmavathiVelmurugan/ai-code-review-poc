def load_changed_files(extract_folder):
    """
    Reads changed_files.txt generated by Jenkins.
    Returns a set of relative Java file paths.
    """

    changed_file_path = os.path.join(
        extract_folder,
        "changed_files.txt"
    )

    if not os.path.exists(changed_file_path):
        print("changed_files.txt not found. Reviewing all Java files.")
        return None

    with open(changed_file_path, "r") as f:
        changed_files = {
            line.strip()
            .replace("\\", "/")
            .split("review_package/")[-1]
            .split("backend/")[-1]
            for line in f
            if line.strip()
        }

    print("\nChanged Files:")
    for file in changed_files:
        print(" -", file)

    return changed_files


def review_project(tar_path):

    extract_folder = tempfile.mkdtemp(prefix="review_")

    reviews = []

    try:

        ##########################################################
        # 1. Extract TAR
        ##########################################################

        print("\n========== EXTRACTING PACKAGE ==========")

        with tarfile.open(tar_path, "r:gz") as tar_ref:
            tar_ref.extractall(extract_folder)

        ##########################################################
        # 2. Load Changed Files
        ##########################################################

        changed_files = load_changed_files(extract_folder)
        changed_lines = {}

        lines_file = os.path.join(extract_folder, "changed_lines.json")

        if os.path.exists(lines_file):
          with open(lines_file) as f:
           changed_lines = json.load(f)

        # Normalize file paths by removing 'backend/'
        normalized_changed_lines = {}

        for path, lines in changed_lines.items():
         clean = path.replace("\\", "/").split("backend/")[-1]
         normalized_changed_lines[clean] = lines

        changed_lines = normalized_changed_lines

        print("========== Normalized Changed Lines ==========")
        print(changed_lines)
        ##########################################################
        # 3. Load Jira Story
        ##########################################################

        jira_story = ""

        jira_file = os.path.join(
            extract_folder,
            "jira-story.json"
        )

        if os.path.exists(jira_file):

            with open(jira_file) as f:
             jira_story = json.load(f)
            print("Jira story loaded successfully")

        ##########################################################
        # 4. Read Java Files
        ##########################################################

        print("\n========== READING JAVA FILES ==========")

        all_java_files = read_java_files(extract_folder)

        java_files = {}

        if isinstance(all_java_files, list):

            java_iterator = [

                (
                    item.get("file") or item.get("path"),
                    item.get("code")

                )

                for item in all_java_files

            ]

        else:

            java_iterator = all_java_files.items()

        ##########################################################
        # Filter only changed Java files
        ##########################################################

        for file_path, code in java_iterator:

            if not file_path or not code:
                continue

            relative_path = os.path.relpath(
                file_path,
                extract_folder
            ).replace("\\", "/")

            clean_path = (
                relative_path
                .split("review_package/")[-1]
                .split("backend/")[-1]
            )

            if changed_files is None or clean_path in changed_files:

                java_files[file_path] = {

                    "code": code,

                    "relative_path": clean_path,

                    "parsed": parse_java_file(code),

                    "chunks": [],

                    "metadata": []

                }

        print(f"Reviewing {len(java_files)} changed Java files")
                ##########################################################
        # 6. Vector Database + AST Chunking
        ##########################################################

        print("\n========== BUILDING VECTOR DATABASE ==========")

        for file_path, data in java_files.items():

            print(f"\nChunking: {data['relative_path']}")

            chunks, metadata = chunk_java_ast(data["code"])
            print("\n========== AST CHUNKS ==========")

            for chunk in chunks:
             print(
              chunk["name"],
              chunk["start_line"],
              chunk["end_line"] )
            modified = changed_lines.get(data["relative_path"], [])
            filtered_chunks = []
            filtered_metadata = []
            for chunk, meta in zip(chunks, metadata):
               print("Chunk type:", type(chunk))
               print("Metadata type:", type(meta))
               print("Metadata:", meta)
            
               start = meta["line"]

               chunk_code = chunk["code"] if isinstance(chunk, dict) else chunk

               end = start + chunk_code.count("\n")
               print(
                   "Checking changed lines:",
                    start,
                     "-",
                      end
                    )

               if any(start <= l <= end for l in modified):

                 filtered_chunks.append(chunk)

                 filtered_metadata.append(meta)

            chunks = filtered_chunks
            metadata = filtered_metadata
            print("Chunks:", len(chunks))
            print("Metadata:", metadata)

            data["chunks"] = chunks
            data["metadata"] = metadata

            print("==============================")
            print("AST CHUNKS")

            for meta in metadata:
                print(meta)

            print("==============================")

            for index, chunk in enumerate(chunks):

                print(f"\nAdding Chunk {index}")
                print("Chunk Type:", type(chunk))
                print("Chunk Preview:")
                print(str(chunk)[:300])

                try:
                    chunk_code = chunk["code"] if isinstance(chunk, dict) else chunk
                    add_chunk(
                        id=f"{data['relative_path']}_{index}",
                        code=chunk_code,
                        file=data["relative_path"]
                    )

                    print(f"Chunk {index} stored successfully.")

                except Exception:

                    print("\n========== ERROR ADDING CHUNK ==========")
                    traceback.print_exc()
                    raise

        print("\nTotal vectors:", collection.count())

        ##########################################################
        # 7. AI REVIEW
        ##########################################################

        print("\n========== STARTING AI REVIEW ==========")

        for file_path, data in java_files.items():

            print(f"\nReviewing: {data['relative_path']}")

            ##################################################
            # SonarQube
            ##################################################

            sonar = get_sonar_issues(
                data["relative_path"]
            )

            ##################################################
            # Neo4j Business Context
            ##################################################

            business_context = "No business context available."

            parsed = data.get("parsed")

            if parsed:

                business_context = (
                    get_business_context(parsed["name"])
                    or
                    "No business context available."
                )

            print("\n========== BUSINESS CONTEXT ==========")
            print(business_context)

            chunk_reviews = []

            ##################################################
            # Review Each Method
            ##################################################

            for chunk, meta in zip(
                data["chunks"],
                data["metadata"]
            ):

                print("\n==============================")
                print("METHOD :", meta["method"])
                print("LINE   :", meta["line"])
                print("==============================")

                print("\nJAVA CODE SENT TO LLM\n")
                chunk_code = chunk["code"] if isinstance(chunk, dict) else chunk

                print(chunk_code[:2000])
                ##################################################
                # Retrieve RAG Context
                ##################################################

                context_chunks = retrieve(

                    chunk_code,

                    exclude_file=data["relative_path"]

                )

                rag_context = "\n\n".join(context_chunks)

                ##################################################
                # LLM Review
                ##################################################

                review = review_code(

                    file_name=data["relative_path"],

                    method_name=meta["method"],

                    code=chunk_code,

                    context=rag_context,

                    business_context=business_context,

                    sonar_issues=sonar,

                    jira_story=jira_story

                )

                print("\n========== REVIEW RESULT ==========")
                print(review)

                chunk_reviews.append({

                    "method": meta["method"],

                    "line": meta["line"],

                    "review": review

                })

            ##################################################
            # Store File Review
            ##################################################

            reviews.append({

                "file": data["relative_path"],

                "chunk_reviews": chunk_reviews

            })

        ##########################################################
        # 8. FINAL RESPONSE
        ##########################################################

        print("\n========== REVIEW COMPLETED ==========")

        return {

            "status": "success",

            "files_reviewed": len(java_files),

            "reviews": reviews

        }

    ##########################################################
    # Exception Handling
    ##########################################################

    except Exception as e:

        print("\n========== REVIEW FAILED ==========")
        traceback.print_exc()

        return {

            "status": "error",

            "message": str(e)

        }

    ##########################################################
    # Cleanup
    ##########################################################

    finally:

        shutil.rmtree(

            extract_folder,

            ignore_errors=True

        )